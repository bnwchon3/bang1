<?php
declare(strict_types=1);
if($action!=='admin_school_logo_upload')return;
// This module is included by admin-config.php *after* require_admin($u).
require_once __DIR__.'/school-branding.php';
must_post();
$id=filter_var($_POST['schoolId']??null,FILTER_VALIDATE_INT);
if(!$id||$id<1)json_out(['success'=>false,'message'=>'กรุณาบันทึกข้อมูลโรงเรียนก่อนแนบรูป'],422);
$school=single('SELECT id,name,logo_file FROM schools WHERE id=?',[$id]);
if(!$school)json_out(['success'=>false,'message'=>'ไม่พบโรงเรียน'],404);
$file=$_FILES['logo']??null;
if(!is_array($file)||($file['error']??UPLOAD_ERR_NO_FILE)!==UPLOAD_ERR_OK){
    $code=(int)($file['error']??UPLOAD_ERR_NO_FILE);
    json_out(['success'=>false,'message'=>$code===UPLOAD_ERR_INI_SIZE||$code===UPLOAD_ERR_FORM_SIZE?
        'ไฟล์มีขนาดใหญ่เกินกว่าที่เซิร์ฟเวอร์อนุญาต':'กรุณาเลือกไฟล์โลโก้ PNG, JPG หรือ WebP'],422);
}
$max=3*1024*1024;
if(($file['size']??0)<=0||$file['size']>$max||
   !is_uploaded_file((string)($file['tmp_name']??'')))
    json_out(['success'=>false,'message'=>'ขนาดรูปต้องไม่เกิน 3 MB'],422);
$tmp=(string)$file['tmp_name'];
$img=@getimagesize($tmp);
if(!is_array($img)||!isset($img[0],$img[1])||$img[0]<64||$img[1]<64
   ||$img[0]>4096||$img[1]>4096)
    json_out(['success'=>false,'message'=>'รูปภาพต้องมีขนาดตั้งแต่ 64 ถึง 4096 พิกเซล'],422);
$mime=(new finfo(FILEINFO_MIME_TYPE))->file($tmp);
$types=['image/png'=>['png',IMAGETYPE_PNG],
        'image/jpeg'=>['jpg',IMAGETYPE_JPEG],
        'image/webp'=>['webp',IMAGETYPE_WEBP]];
if(!is_string($mime)||!isset($types[$mime])||($img[2]??0)!==$types[$mime][1])
    json_out(['success'=>false,'message'=>'รองรับเฉพาะรูปภาพ PNG, JPG หรือ WebP ที่ถูกต้องเท่านั้น'],422);
// Original filename is never written to the web server. The public upload
// directory can only contain validated non-executable image extensions.
$directory=__DIR__.'/uploads/school-logos';
if(!is_dir($directory)&&!@mkdir($directory,0755,true)&&!is_dir($directory))
    json_out(['success'=>false,'message'=>'ไม่สามารถสร้างพื้นที่จัดเก็บโลโก้บนโฮสต์'],500);
if(!is_writable($directory))json_out(['success'=>false,'message'=>'พื้นที่จัดเก็บโลโก้ไม่อนุญาตให้เขียนไฟล์'],500);
$name='school-'.$id.'-'.bin2hex(random_bytes(12)).'.'.$types[$mime][0];
$target=$directory.'/'.$name;
if(!move_uploaded_file($tmp,$target))
    json_out(['success'=>false,'message'=>'อัปโหลดโลโก้ไม่สำเร็จ กรุณาลองอีกครั้ง'],500);
@chmod($target,0644);
$old=(string)($school['logo_file']??'');
try{
    db()->prepare('UPDATE schools SET logo_file=?,logo_updated_at=NOW() WHERE id=?')
        ->execute([$name,$id]);
}catch(Throwable $e){
    @unlink($target);
    error_log('Bang1 school logo update: '.$e->getMessage());
    json_out(['success'=>false,'message'=>'บันทึกข้อมูลรูปสัญลักษณ์ไม่สำเร็จ'],500);
}
// Delete the old logo only AFTER the new one has been saved successfully;
// cleanup is confined to paths generated by this upload endpoint.
if($old!==''&&$old!==$name&&school_logo_url($old)){
    $oldPath=$directory.'/'.$old;
    if(is_file($oldPath))@unlink($oldPath);
}
log_action('ADMIN_SCHOOL_LOGO_UPLOAD',$u,'School',(string)$id,
    'School emblem replaced: '.$school['name']);
json_out(['success'=>true,'id'=>$id,'logoUrl'=>school_logo_url($name),
    'message'=>'บันทึกตราสัญลักษณ์โรงเรียนเรียบร้อย']);
